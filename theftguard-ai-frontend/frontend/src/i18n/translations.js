/**
 * Resolves a translation string for a given key, language, and interpolation parameters.
 * Falls back to English if the key is missing in target language, or key itself if missing in both.
 */
export function t(key, lang = 'en', params = {}) {
  const effectiveLang = ['en', 'hi', 'te'].includes(lang) ? lang : 'en'
  const dict = translations[effectiveLang] || translations.en
  const parts = String(key || '').split('.')

  let val = dict
  for (const p of parts) {
    if (val && typeof val === 'object' && p in val) {
      val = val[p]
    } else {
      val = null
      break
    }
  }

  // Fallback to English
  if (val == null) {
    let fallbackVal = translations.en
    for (const p of parts) {
      if (fallbackVal && typeof fallbackVal === 'object' && p in fallbackVal) {
        fallbackVal = fallbackVal[p]
      } else {
        fallbackVal = null
        break
      }
    }
    val = fallbackVal != null ? fallbackVal : key
  }

  if (typeof val === 'string' && Object.keys(params).length > 0) {
    return val.replace(/\{(\w+)\}/g, (_, k) => (params[k] != null ? params[k] : `{${k}}`))
  }

  return val != null ? val : key
}
